'use strict';
const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { prepareRelease } = require('./prepare-release');
const temporary = fs.mkdtempSync(path.join(os.tmpdir(), 'uma-release-test-'));
try {
  const root = path.join(temporary, 'source');
  fs.mkdirSync(path.join(root, 'uma_tools'), { recursive: true });
  const html = '<head><link rel="stylesheet" href="/uma_tools/base.css"><link rel="stylesheet" href="/uma_tools/detail.css"><script src="/uma_tools/app.js"></script><script type="module" src="/uma_tools/image-viewer.js"></script></head>';
  fs.writeFileSync(path.join(root, 'uma_tools/base.css'), '.card{color:red}');
  fs.writeFileSync(path.join(root, 'uma_tools/detail.css'), '.card{color:blue}');
  fs.writeFileSync(path.join(root, '赛马娘LIVE相关.html'), html);
  fs.writeFileSync(path.join(root, 'uma_tools/app.js'), 'import { value } from "/uma_tools/shared.js"; globalThis.startupValue = value; load("/uma_tools/child.js"); load("/data/index.js");');
  fs.writeFileSync(path.join(root, 'uma_tools/shared.js'), 'export const value = 42;');
  fs.writeFileSync(path.join(root, 'uma_tools/child.js'), 'const value = 1;');
  fs.copyFileSync(path.join(__dirname, '../uma_tools/image-viewer.js'), path.join(root, 'uma_tools/image-viewer.js'));
  const vendor = path.join(root, 'uma_tools/vendor/photoswipe/photoswipe.esm.min.js');
  fs.mkdirSync(path.dirname(vendor), { recursive: true });
  fs.writeFileSync(vendor, 'export default class PhotoSwipe {}');
  const commit = 'a'.repeat(40);
  const first = prepareRelease(root, commit);
  const publishedHtml = fs.readFileSync(path.join(root, '赛马娘LIVE相关.html'), 'utf8');
  const styles = [...publishedHtml.matchAll(/rel="stylesheet" href="([^"]+)"/g)];
  assert.strictEqual(styles.length, 1, 'publication combines render-blocking styles into one request');
  assert.strictEqual(fs.readFileSync(path.join(root, styles[0][1]), 'utf8'), '.card{color:red}\n.card{color:blue}', 'the CSS cascade order survives publication');
  const firstApp = fs.readFileSync(path.join(root, first.assets['/uma_tools/app.js']), 'utf8');
  assert(!/\bfrom\s*["']/.test(firstApp), 'the startup static graph has no follow-up module requests');
  const context = { load() {} };
  require('vm').runInNewContext(firstApp, context);
  assert.strictEqual(context.startupValue, 42, 'bundling retains imported runtime behavior');
  assert(firstApp.includes(first.assets['/uma_tools/child.js']), 'lazy loader references its exact dependency');
  assert(firstApp.includes('/data/index.js'), 'mutable data is not bundled into immutable assets');
  const viewer = fs.readFileSync(path.join(root, first.assets['/uma_tools/image-viewer.js']), 'utf8');
  const sdk = first.assets['/uma_tools/vendor/photoswipe/photoswipe.esm.min.js'];
  assert(sdk && viewer.includes("import PhotoSwipe from '" + sdk + "'"), 'the production viewer imports its published SDK resource');
  const oldChild = fs.readFileSync(path.join(root, first.assets['/uma_tools/child.js']), 'utf8');
  fs.writeFileSync(path.join(root, '赛马娘LIVE相关.html'), html);
  fs.writeFileSync(path.join(root, 'uma_tools/child.js'), 'const value = 2;');
  fs.writeFileSync(vendor, 'export default class PhotoSwipe { version = 2; }');
  const second = prepareRelease(root, 'b'.repeat(40));
  assert.notStrictEqual(first.assets['/uma_tools/app.js'], second.assets['/uma_tools/app.js'], 'changing a lazy dependency changes the parent asset address');
  assert.notStrictEqual(first.assets['/uma_tools/image-viewer.js'], second.assets['/uma_tools/image-viewer.js'], 'changing the SDK also versions its importing module');
  assert.strictEqual(fs.readFileSync(path.join(root, first.assets['/uma_tools/child.js']), 'utf8'), oldChild, 'previous browser tabs can still read their original resource');
  assert(fs.readFileSync(path.join(root, '赛马娘LIVE相关.html'), 'utf8').includes('content="' + 'b'.repeat(40) + '"'));
  console.log('release resource identity and previous-tab regressions passed');
} finally { fs.rmSync(temporary, { recursive: true, force: true }); }
