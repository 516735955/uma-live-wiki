'use strict';

const assert = require('assert');
const fs = require('fs');
const os = require('os');
const path = require('path');
const { run } = require('./localize_entities');

(async () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'uma-localize-'));
  fs.mkdirSync(path.join(root, 'data/anime'), { recursive: true });
  fs.mkdirSync(path.join(root, 'data/auto_update'), { recursive: true });
  fs.mkdirSync(path.join(root, 'uma_tools'), { recursive: true });
  fs.copyFileSync(path.join(__dirname, 'translation-glossary.json'), path.join(root, 'uma_tools/translation-glossary.json'));
  fs.writeFileSync(path.join(root, 'data/character_index_data.js'), 'window.CHAR_INDEX = [];');
  fs.writeFileSync(path.join(root, 'data/voice_actor_profiles.json'), '{"voice_actors":[]}');
  fs.writeFileSync(path.join(root, 'data/horses_details.js'), 'window.HORSES_DETAIL = {"h":{"id":"h","ja":"馬","zh":"马","intro":["日本語の説明"],"wiki":{"lang":"ja"}}};');
  fs.writeFileSync(path.join(root, 'data/anime/works.json'), JSON.stringify({ works: [{ id: 'w', title_ja: '日本語の作品', title_zh: '人工作品名', summary_ja: '番組の紹介', summary_zh: '已有人工简介' }] }));
  fs.writeFileSync(path.join(root, 'data/anime/units.json'), JSON.stringify({ series: [{ work_id: 'w', details: { '1': { summary_ja: '第一話の説明', summary_zh: '第一话中文' } } }] }));
  fs.writeFileSync(path.join(root, 'data/character_detail_data.js'), `window.CHAR_DETAIL = ${JSON.stringify({ c: { html: '<p>已有中文</p><span lang="ja">キャラ</span>' } })};`);
  const result = await run(root, { noApi: true, initialize: true });
  assert.strictEqual(result.pending, 1, 'initialize creates a manual baseline without API calls');
  assert.strictEqual(result.entities, 3, 'anime work, episode and horse explanation are indexed');
  await run(root, { noApi: true, scope: 'anime', rebuild: false });
  const scopedArchive = JSON.parse(fs.readFileSync(path.join(root, 'data/auto_update/entity_localizations.json')));
  assert(scopedArchive.pending.some(item => item.key === 'horse:h:intro:0'), 'scoped anime run preserves the horse queue');
  let calls = 0;
  const translate = async () => { calls++; return '新增的中文说明'; };
  await run(root, { noApi: true, translate });
  assert.strictEqual(calls, 0, 'the existing untranslated historical baseline waits for manual translation');
  const horseFile = path.join(root, 'data/horses_details.js');
  const vm = require('vm');
  const readHorse = () => { const context = { window: {} }; vm.runInNewContext(fs.readFileSync(horseFile, 'utf8'), context); return context.window.HORSES_DETAIL; };
  const writeHorse = value => fs.writeFileSync(horseFile, 'window.HORSES_DETAIL = '+JSON.stringify(value)+';');
  let horses = readHorse(); horses.h.intro.push('新しい日文の説明'); writeHorse(horses);
  await run(root, { noApi: true, translate });
  assert.strictEqual(calls, 1, 'only the new paragraph is translated');
  assert.strictEqual(readHorse().h.intro[1], '新增的中文说明', 'the field read by the page uses the archived translation');
  horses = readHorse(); horses.h.intro[1] = '新しい日文の説明'; writeHorse(horses);
  await run(root, { noApi: true, translate });
  assert.strictEqual(calls, 1, 'a fresh source fetch with the same text reuses its translation');
  assert.strictEqual(readHorse().h.intro[1], '新增的中文说明');
  horses = readHorse(); horses.h.intro[1] = '変更された日文の説明'; writeHorse(horses);
  await run(root, { noApi: true, translate });
  assert.strictEqual(calls, 2, 'only changed source text triggers another translation');
  const archive = JSON.parse(fs.readFileSync(path.join(root, 'data/auto_update/entity_localizations.json')));
  assert(!archive.pending.some(item => item.key === 'horse:h:intro:1'), 'success removes the pending task');
  const workFile = path.join(root, 'data/anime/works.json');
  const works = JSON.parse(fs.readFileSync(workFile));
  works.works.push({ id: 'new', title_ja: '新番組', summary_ja: '新番組の説明' });
  fs.writeFileSync(workFile, JSON.stringify(works));
  await run(root, { noApi: true, translate, rebuild: false });
  const newSource = JSON.parse(fs.readFileSync(workFile));
  newSource.works.find(row => row.id === 'new').summary_ja = '変更後の番組説明';
  fs.writeFileSync(workFile, JSON.stringify(newSource));
  const fail = async () => '';
  await run(root, { noApi: true, translate: fail, rebuild: false });
  await run(root, { noApi: true, translate: fail, rebuild: false });
  const pendingArchive = JSON.parse(fs.readFileSync(path.join(root, 'data/auto_update/entity_localizations.json')));
  assert(pendingArchive.pending.some(row => row.key === 'anime-work:new' && row.field === 'summary'), 'changed original remains pending after repeated failed attempts');
  assert.strictEqual(JSON.parse(fs.readFileSync(workFile)).works.find(row => row.id === 'new').summary_zh, '', 'stale machine translation is not accepted for changed source');
  const manualRecovery = JSON.parse(fs.readFileSync(workFile));
  manualRecovery.works.find(row => row.id === 'new').summary_zh = '人工补齐的新介绍';
  fs.writeFileSync(workFile, JSON.stringify(manualRecovery));
  await run(root, { noApi: true, translate: fail, rebuild: false });
  const recoveredArchive = JSON.parse(fs.readFileSync(path.join(root, 'data/auto_update/entity_localizations.json')));
  assert.equal(recoveredArchive.records['anime-work:new'].summary_translator, 'accepted');
  assert(!recoveredArchive.pending.some(row => row.key === 'anime-work:new' && row.field === 'summary'), 'a reviewed same-source correction removes the stale pending task');
  const reviewed = JSON.parse(fs.readFileSync(workFile));
  reviewed.works[0].summary_ja = '手動確認が必要な変更';
  fs.writeFileSync(workFile, JSON.stringify(reviewed));
  const before = calls;
  await run(root, { noApi: true, translate, rebuild: false });
  assert.strictEqual(calls, before, 'accepted corrections are retained while changed reviewed sources stay pending for manual review');
  const finalArchive = JSON.parse(fs.readFileSync(path.join(root, 'data/auto_update/entity_localizations.json')));
  assert(finalArchive.pending.some(row => row.key === 'anime-work:w' && row.field === 'summary' && row.owner === 'assistant'));
  fs.rmSync(root, { recursive: true, force: true });
  console.log('entity localization fixtures: ok');
})().catch(error => { console.error(error); process.exitCode = 1; });
