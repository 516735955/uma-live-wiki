'use strict';

const assert = require('assert');
const routes = require('./route-utils');

assert.strictEqual(routes.home(), '/zh-Hans/');
assert.strictEqual(routes.news('42'), '/zh-Hans/news/42');
assert.strictEqual(routes.events('live-6th', 'day-2'), '/zh-Hans/events/live-6th/sessions/day-2');
assert.strictEqual(routes.songs('song-1'), '/zh-Hans/music/songs/song-1');
assert.strictEqual(routes.songs('song-1', 'lyrics'), '/zh-Hans/music/songs/song-1/lyrics');
assert.strictEqual(routes.albums('album-laca-25001'), '/zh-Hans/music/albums/album-laca-25001');
assert.strictEqual(routes.creators('creator-1', 'collaborators'), '/zh-Hans/music/creators/creator-1/collaborators');
assert.strictEqual(routes.characters('specialweek', 'pedigree'), '/zh-Hans/database/characters/specialweek/pedigree');
assert.strictEqual(routes.voiceActors('waki-azumi', 'songs'), '/zh-Hans/database/voice-actors/waki-azumi/songs');
assert.strictEqual(routes.sections.character.includes('appearances'), false);
assert.strictEqual(routes.sections.voiceActor.includes('appearances'), false);
assert.strictEqual(routes.characters('specialweek', 'appearances'), '/zh-Hans/database/characters/specialweek/events');
assert.strictEqual(routes.voiceActors('waki-azumi', 'appearances'), '/zh-Hans/database/voice-actors/waki-azumi/events');
assert.strictEqual(routes.resolve('/zh-Hans/database/characters/specialweek/appearances?x=1'), '/zh-Hans/database/characters/specialweek/events?x=1');
assert.strictEqual(routes.resolve('/zh-Hans/database/characters/specialweek?section=appearances&x=1'), '/zh-Hans/database/characters/specialweek/events?x=1');
assert.strictEqual(routes.resolve('/zh-Hans/database/voice-actors/va-0040?section=events'), '/zh-Hans/database/voice-actors/va-0040/events');
assert.strictEqual(routes.resolve('/zh-Hans/database/characters/specialweek/?section=songs&x=1'), '/zh-Hans/database/characters/specialweek/songs?x=1');
assert.strictEqual(routes.resolve('/zh-Hans/events?series=missing&q=Uma', {eventSeries:['real']}), '/zh-Hans/events?q=Uma');
assert.strictEqual(routes.resolve('/zh-Hans/music/albums?work=missing&type=missing&year=2020', {albumYears:['2025']}), '/zh-Hans/music/albums');
assert.strictEqual(routes.resolve('/zh-Hans/database/characters/specialweek/anime?section=appearances'), '/zh-Hans/database/characters/specialweek/anime');
assert.strictEqual(routes.resolve('/zh-Hans/database/voice-actors/waki-azumi/appearances?section=appearances'), '/zh-Hans/database/voice-actors/waki-azumi/events');
assert.strictEqual(routes.resolve('https://example.com/characters/specialweek/appearances'), '/characters/specialweek/appearances');
assert.strictEqual(routes.resolve('/zh-Hans/database/characters?section=appearances'), '/zh-Hans/database/characters?section=appearances');
assert.strictEqual(routes.resolve('/zh-Hans/database/anime?year=2025&format=web_short&q=x'), '/zh-Hans/database/anime?format=short&q=x');
assert.strictEqual(routes.resolve('/zh-Hans/database/anime/anime-umayuru?year=2025&format=web_short'), '/zh-Hans/database/anime/anime-umayuru?year=2025&format=web_short');
assert.strictEqual(routes.anime(), '/zh-Hans/database/anime');
assert.strictEqual(routes.anime('anime-s1'), '/zh-Hans/database/anime/anime-s1');
assert.strictEqual(routes.anime('anime-s1', 'anime-s1-e01'), '/zh-Hans/database/anime/anime-s1/episodes/anime-s1-e01');
assert.strictEqual(routes.staff('staff-1'), '/zh-Hans/database/staff/staff-1');
assert.strictEqual(routes.other(), '/zh-Hans/database/other');
assert.strictEqual(routes.horses('special-week'), '/zh-Hans/database/horses/special-week');
assert.strictEqual(routes.relationships(), '/zh-Hans/database/relationships');
assert.strictEqual(routes.videos(), '/zh-Hans/resources/videos');
assert.strictEqual(routes.query(routes.songs(), { q: 'GIRLS\' LEGEND U', page: 2 }), '/zh-Hans/music/songs?q=GIRLS%27+LEGEND+U&page=2');

console.log('route registry ok');
